@pytest.mark.parametrize("name,expected", CASES)
def test_keyword_group(name, expected):
    assert keyword_group(name) == expected


def test_unknown_name_is_left_for_the_model():
    assert keyword_group("Изделие 12345 без понятных слов") is None
    assert keyword_group(None) is None


def test_groups_fit_laya_choice_limit():
    assert OTHER in GROUPS
    assert len(GROUPS) <= 20  # у Laya качество choice падает на >20 вариантах
    assert all(GROUPS.values())  # у каждой группы есть описание для модели


def test_rule_wins_over_model():
    assert decide("Розетки и выключатели", "Щиты и боксы", 0.9) == ("Розетки и выключатели", 1.0, "rules")


def test_confident_model_fills_the_gap():
    assert decide(None, "Щиты и боксы", 0.93) == ("Щиты и боксы", 0.93, "laya")


def test_unsure_model_goes_to_other():
    assert decide(None, "Щиты и боксы", 0.31) == (OTHER, 0.31, "laya_low_confidence")


def test_missing_rule_from_pandas_nan_is_not_a_rule():
    assert decide(float("nan"), "Щиты и боксы", 0.95) == ("Щиты и боксы", 0.95, "laya")
